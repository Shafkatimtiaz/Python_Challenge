#WAP to Input Two Numbeers and Print There Addition,Subtraction,Multiplication,Division,square,cube.
number_1=int(input("Enter The 1st Number :-"))
number_2=int(input("Enter The 2nd Number :-"))
print(f"Addition of {number_1} & {number_2} is {number_1 + number_2}")
print(f"Subtraction of {number_1} & {number_2} is {number_1 - number_2}")
print(f"Multiplication of {number_1} & {number_2} is {number_1 * number_2}")
print(f"Division of {number_1} & {number_2} is {number_1 / number_2}")
print(f"Square of {number_1} & {number_2} is {number_1**2} & {number_2**2}")
print(f"Cube of {number_1} & {number_2} is {number_1**3} & {number_2**3}")