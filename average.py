#WAP to Take Three Integers As Input And Print There Average.
number_1=int(input("Enter The 1st Number:- "))
number_2=int(input("Enter The 2nd Number:- "))
number_3=int(input("Enter The 3rd Number:- "))
sum=(number_1+number_2+number_3)
average=(sum/3)
print(f"The Average of {number_1},{number_2} & {number_3} is {average}.")